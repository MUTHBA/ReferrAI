# Database insertion (admin "generate synthetic data")
# ---------------------------------------------------------------------------


async def insert_world(session, world: SyntheticWorld, max_conversions: Optional[int] = None) -> dict:
    """Persist a world as is_synthetic=True rows in one transaction.

    Rows are flushed table by table (parents before children) because the ORM
    models declare no relationship()s for the unit of work to order by.
    Labels are not stored. Returns row counts.
    """
    from decimal import Decimal

    from app.models.partner import Partner
    from app.models.referral import ReferralClick, ReferralConversion, ReferralLink
    from app.models.user import User
    from app.models.wallet import Wallet

    users, partners, wallets, links = [], [], [], {}
    for p in world.partners:
        uid = uuid.uuid4()
        users.append(User(id=uid, email=p.email, password_hash="!synthetic-no-login", role="partner", is_active=False))
        partners.append(
            Partner(
                id=p.snapshot.id, user_id=uid, name=p.name, email=p.email, category=p.category,
                status="active", is_synthetic=True, created_at=p.snapshot.created_at,
            )
        )
        wallets.append(Wallet(id=uuid.uuid4(), partner_id=p.snapshot.id))
        links[p.snapshot.id] = ReferralLink(
            id=uuid.uuid4(), partner_id=p.snapshot.id, slug=f"syn-{uuid.uuid4().hex[:12]}",
            destination_url="https://example.com/synthetic", is_active=False,
        )

    session.add_all(users)
    await session.flush()
    session.add_all(partners)
    await session.flush()
    session.add_all(wallets + list(links.values()))
    await session.flush()

    session.add_all(
        ReferralClick(
            id=c.event.id, referral_link_id=links[c.event.partner_id].id, partner_id=c.event.partner_id,
            ip_address=c.event.ip,
            device_info={"user_agent": c.event.user_agent, "device_type": c.event.device_type, "fingerprint": c.event.fingerprint},
            source=c.event.source, clicked_at=c.event.ts, is_synthetic=True,
        )
        for c in world.clicks
    )
    await session.flush()

    convs = world.conversions if max_conversions is None else world.conversions[:max_conversions]
    session.add_all(
        ReferralConversion(
            id=c.event.id, partner_id=c.event.partner_id, click_id=c.event.click_id,
            referral_link_id=links[c.event.partner_id].id, external_reference=f"synthetic-{c.event.id.hex}",
            conversion_value=Decimal(str(c.event.value)), attribution_model="last_click",
            converted_at=c.event.ts, is_synthetic=True,
        )
        for c in convs
    )
    await session.flush()
    await session.commit()
    return {"partners_created": len(partners), "clicks_created": len(world.clicks), "conversions_created": len(convs)}
