# -----------------------------------------------------------------------------
# backend/app/ai/synthetic.py
#
# Deterministic synthetic "world" used to train the models (and, via the
# admin endpoint, to populate is_synthetic=True demo rows). Nothing here
# touches the database except insert_world().
#
# Each simulated partner has hidden traits that drive behaviour:
#   quality   (0-1)  -> traffic mix (search/email vs. social/other), order
#                       values, conversion rate and how often referrals are good
#   activity  (clicks/day)
#   churn day         -> activity fades over ~3 weeks, then mostly stops
#   fraud ring member -> bursts of clicks from a few IPs, bot user agents and
#                       device fingerprints shared with other ring members
# Labels produced (never stored in the DB):
#   click.fraud           1 for clicks generated by a fraud burst
#   conversion.good       "good referral" outcome (e.g. not refunded) — drawn
#                         from the partner's quality, traffic source, device and
#                         fraud status, NOT derived from any single feature
#   churn                 computed from future activity in features/training
# -----------------------------------------------------------------------------

from __future__ import annotations

import math
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from typing import Optional

import numpy as np

from app.ai.features import ClickEvent, ConversionEvent, PartnerSnapshot, fingerprint_for

_UAS = {
    "desktop": [
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/128.0 Safari/537.36",
        "Mozilla/5.0 (Macintosh; Intel Mac OS X 14_5) AppleWebKit/605.1.15 Version/17.5 Safari/605.1.15",
        "Mozilla/5.0 (X11; Linux x86_64; rv:129.0) Gecko/20100101 Firefox/129.0",
    ],
    "mobile": [
        "Mozilla/5.0 (iPhone; CPU iPhone OS 17_5 like Mac OS X) AppleWebKit/605.1.15 Mobile/15E148",
        "Mozilla/5.0 (Linux; Android 14; Pixel 8) AppleWebKit/537.36 Chrome/128.0 Mobile Safari/537.36",
    ],
    "tablet": ["Mozilla/5.0 (iPad; CPU OS 17_5 like Mac OS X) AppleWebKit/605.1.15 Mobile/15E148"],
    "bot": ["python-requests/2.32", "Mozilla/5.0 (compatible; HeadlessChrome/128.0)", "curl/8.6.0"],
}
_SOURCES = {
    "search": ["google", "bing"],
    "email": ["newsletter", "email"],
    "social": ["facebook", "instagram", "tiktok"],
    "direct": [None],
    "other": ["coupon-site", "forum"],
}
_CATEGORIES = ["fitness", "fashion", "electronics", "travel", "food", "finance", "beauty", "gaming"]


@dataclass
class SimPartner:
    snapshot: PartnerSnapshot
    name: str
    email: str
    category: str
    quality: float
    activity: float
    churn_day: Optional[float]
    fraud: bool


@dataclass
class SimClick:
    event: ClickEvent
    fraud: int


@dataclass
class SimConversion:
    event: ConversionEvent
    good: int


@dataclass
class SyntheticWorld:
    start: datetime
    end: datetime
    partners: list[SimPartner] = field(default_factory=list)
    clicks: list[SimClick] = field(default_factory=list)
    conversions: list[SimConversion] = field(default_factory=list)


def _sigmoid(x: float) -> float:
    return 1.0 / (1.0 + math.exp(-x))


def _ip(rng: np.random.Generator) -> str:
    a, b, c, d = rng.integers(1, 254, size=4)
    return f"{a}.{b}.{c}.{d}"


def _uuid(rng: np.random.Generator) -> uuid.UUID:
    """Seeded UUID so the same seed always produces the same world."""
    return uuid.UUID(bytes=rng.bytes(16), version=4)


def _pick(rng: np.random.Generator, seq):
    """Fast uniform choice from a Python sequence (np.choice is slow per call)."""
    return seq[int(rng.random() * len(seq))]


def _pick_weighted(rng: np.random.Generator, seq, cum):
    r = rng.random() * cum[-1]
    for item, edge in zip(seq, cum):
        if r < edge:
            return item
    return seq[-1]


def generate_world(
    n_partners: int = 300,
    days: int = 180,
    fraud_ratio: float = 0.1,
    churn_ratio: float = 0.3,
    clicks_per_day: float = 0.8,
    seed: int = 7,
    end: Optional[datetime] = None,
) -> SyntheticWorld:
    rng = np.random.default_rng(seed)
    end = end or datetime.now(timezone.utc).replace(microsecond=0)
    start = end - timedelta(days=days)
    world = SyntheticWorld(start=start, end=end)

    n_fraud = int(round(n_partners * fraud_ratio))
    ring_size = 4
    rings = [
        [fingerprint_for(_ip(rng), str(_pick(rng, _UAS["bot"]))) for _ in range(3)]
        for _ in range(max(1, math.ceil(n_fraud / ring_size)))
    ]

    for i in range(n_partners):
        fraud = i < n_fraud
        quality = float(rng.beta(2, 2)) if not fraud else float(rng.beta(1.2, 4))
        activity = float(np.clip(rng.lognormal(math.log(clicks_per_day), 0.8), 0.1, 25))
        churn_day = float(rng.uniform(15, days - 10)) if rng.random() < churn_ratio else None
        tenure_days = float(rng.uniform(30, 600))
        created = start - timedelta(days=max(0.0, tenure_days - days * rng.random()))
        tier = 1 + int(quality > 0.55) + int(quality > 0.8 and activity > clicks_per_day)
        pid = _uuid(rng)
        world.partners.append(
            SimPartner(
                snapshot=PartnerSnapshot(id=pid, created_at=created, tier_rank=tier),
                name=f"Synthetic Partner {i + 1}",
                email=f"synthetic-{pid.hex[:12]}@synthetic.referrai.local",
                category=_pick(rng, _CATEGORIES),
                quality=quality,
                activity=activity,
                churn_day=churn_day,
                fraud=fraud,
            )
        )

    for idx, p in enumerate(world.partners):
        ring = rings[idx // ring_size] if p.fraud else None
        _simulate_partner(world, p, rng, days, ring)

    world.clicks.sort(key=lambda c: c.event.ts)
    world.conversions.sort(key=lambda c: c.event.ts)
    return world


_SOURCE_NAMES = ["search", "email", "social", "direct", "other"]
_DEVICES = ["desktop", "mobile", "tablet", "bot"]
_DEVICE_CUM = [0.46, 0.90, 0.98, 1.0]


def _source_cum(quality: float) -> list[float]:
    w = [0.15 + 0.35 * quality, 0.05 + 0.25 * quality, 0.45 - 0.3 * quality, 0.2, 0.15 - 0.1 * quality]
    return list(np.cumsum(np.clip(w, 0.01, None)))


def _simulate_partner(world: SyntheticWorld, p: SimPartner, rng, days: int, ring) -> None:
    pid = p.snapshot.id
    created_day = max(0.0, (p.snapshot.created_at - world.start).total_seconds() / 86400.0)
    home_ips = [_ip(rng) for _ in range(int(rng.integers(20, 200)))]
    src_cum = _source_cum(p.quality)

    for day in range(int(created_day), days):
        rate = p.activity
        if p.churn_day is not None:
            if day >= p.churn_day:
                rate *= 0.03
            elif day >= p.churn_day - 21:
                rate *= max(0.1, (p.churn_day - day) / 21.0)
        n = int(rng.poisson(rate))
        for _ in range(n):
            ts = world.start + timedelta(days=day, seconds=float(rng.uniform(0, 86400)))
            device = _pick_weighted(rng, _DEVICES, _DEVICE_CUM)
            ua = _pick(rng, _UAS[device])
            ip = _pick(rng, home_ips) if rng.random() < 0.3 else _ip(rng)
            stype = _pick_weighted(rng, _SOURCE_NAMES, src_cum)
            click = ClickEvent(
                id=_uuid(rng), partner_id=pid, ts=ts, ip=ip, user_agent=ua, device_type=device,
                source=_pick(rng, _SOURCES[stype]), fingerprint=fingerprint_for(ip, ua),
            )
            world.clicks.append(SimClick(click, 0))
            _maybe_convert(world, p, click, stype, rng, fraud_click=False)

        # Fraud bursts: a few times a month, many clicks within minutes.
        if ring is not None and (p.churn_day is None or day < p.churn_day) and rng.random() < 0.03:
            burst_start = world.start + timedelta(days=day, seconds=float(rng.uniform(0, 80000)))
            ips = [_ip(rng) for _ in range(int(rng.integers(1, 4)))]
            for _ in range(int(rng.integers(15, 60))):
                ts = burst_start + timedelta(seconds=float(rng.exponential(25)))
                burst_start = ts
                bot = rng.random() < 0.6
                device = "bot" if bot else "mobile"
                ua = _pick(rng, _UAS[device])
                fp = _pick(rng, ring) if rng.random() < 0.7 else fingerprint_for(ips[0], ua)
                click = ClickEvent(
                    id=_uuid(rng), partner_id=pid, ts=ts, ip=_pick(rng, ips), user_agent=ua,
                    device_type=device, source=_pick(rng, _SOURCES["other"]), fingerprint=fp,
                )
                world.clicks.append(SimClick(click, 1))
                _maybe_convert(world, p, click, "other", rng, fraud_click=True)


_SOURCE_EFFECT = {"search": 0.6, "email": 0.8, "social": -0.3, "direct": 0.2, "other": -0.6}
_DEVICE_EFFECT = {"desktop": 0.2, "mobile": 0.0, "tablet": 0.1, "bot": -2.5, "unknown": 0.0}


def _maybe_convert(world, p: SimPartner, click: ClickEvent, stype: str, rng, fraud_click: bool) -> None:
    if fraud_click:
        p_conv = 0.015
    else:
        p_conv = _sigmoid(-3.0 + 2.2 * p.quality + 0.5 * _SOURCE_EFFECT[stype] + _DEVICE_EFFECT[click.device_type])
    if rng.random() >= p_conv:
        return
    hours = float(rng.exponential(0.05)) if fraud_click else float(rng.lognormal(math.log(6), 1.2))
    ts = click.ts + timedelta(hours=hours)
    if ts > world.end:
        return
    value = float(np.clip(rng.lognormal(math.log(40 + 160 * p.quality), 0.6), 5, 5000))
    logit = (
        -1.2
        + 3.2 * p.quality
        + _SOURCE_EFFECT[stype]
        + 0.5 * _DEVICE_EFFECT[click.device_type]
        - 0.35 * abs(math.log1p(hours) - math.log1p(6))
        - (3.0 if fraud_click else 0.0)
        + float(rng.normal(0, 0.6))
    )
    good = int(rng.random() < _sigmoid(logit))
    world.conversions.append(
        SimConversion(ConversionEvent(id=_uuid(rng), partner_id=p.snapshot.id, ts=ts, value=round(value, 2), click_id=click.id), good)
    )


